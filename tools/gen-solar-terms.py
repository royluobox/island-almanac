"""生成二十四节气日期表（1901–2100）：

    Data/solar-terms-1901-2100.txt   人类可读的中间产物（每年一行，24 项 MMDD）
    Core/SolarTermsData.cs           编译进插件的 C# 表

只在需要更新数据时跑；插件运行期不依赖 lunar-python，也不联网。

依赖：
    pip install lunar-python

用法：
    python tools/gen-solar-terms.py
"""

import io
import os

from lunar_python import Solar

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIRST_YEAR = 1901
LAST_YEAR = 2100

# 一次取一年的节气表可能缺头缺尾，所以取「当年 1 月 15 日」和「次年 1 月 15 日」两张表，
# 按日期升序合并后正好 24 项（小寒 → 冬至）。
rows = []
for year in range(FIRST_YEAR, LAST_YEAR + 1):
    seen = {}
    for probe in (year, year + 1):
        table = Solar.fromYmd(probe, 1, 15).getLunar().getJieQiTable()
        for _, solar in table.items():
            if solar.getYear() == year:
                seen[solar.toYmd()] = (solar.getMonth(), solar.getDay())

    dates = sorted(seen)
    assert len(dates) == 24, f"{year} 年只有 {len(dates)} 个节气"
    rows.append("".join("%02d%02d" % seen[d] for d in dates))

txt = os.path.join(ROOT, "Data", "solar-terms-1901-2100.txt")
with open(txt, "w", encoding="ascii") as fh:
    fh.write("\n".join(rows))

out = io.StringIO()
out.write("// <auto-generated>\n")
out.write("// 二十四节气日期表，1901-2100 年。每年 24 项，按节气顺序（小寒→冬至），每项 4 位 MMDD。\n")
out.write("// 数据由 lunar_python（寿星天文历算法）离线生成，见 tools/gen-solar-terms.py；\n")
out.write("// 已与日本国立天文台 2026/2027 历要项逐项核对（东九区换算为东八区后完全一致）。\n")
out.write("// 仅为日期粒度数据，不联网、不随时间变化。\n")
out.write("// </auto-generated>\n\n")
out.write("namespace IslandAlmanac.Core;\n\n")
out.write("internal static class SolarTermsData\n{\n")
out.write(f"    internal const int FirstYear = {FIRST_YEAR};\n\n")
out.write("    internal static readonly string[] Rows =\n    {\n")
for i, row in enumerate(rows):
    out.write(f'        "{row}", // {FIRST_YEAR + i}\n')
out.write("    };\n}\n")

cs = os.path.join(ROOT, "Core", "SolarTermsData.cs")
with open(cs, "w", encoding="utf-8") as fh:
    fh.write(out.getvalue())

print(f"{FIRST_YEAR}–{LAST_YEAR}：{len(rows)} 行")
print(f"写入 {txt}")
print(f"写入 {cs}")
